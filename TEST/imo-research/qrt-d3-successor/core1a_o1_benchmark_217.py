    thread=threading.Thread(target=server.serve_forever,daemon=True)
    thread.start()
    observations=[]
    try:
        with sync_playwright() as pl:
            browser=pl.chromium.launch(headless=True,args=["--no-sandbox"])
            try:
                for width in (390,768,1280):
                    page=browser.new_page(viewport={"width":width,"height":900})
                    errors=[]
                    failed=[]
                    http_errors=[]
                    page.on("pageerror",lambda exc:errors.append(str(exc)))
                    page.on("requestfailed",lambda request:failed.append(request.url))
                    page.on("response",lambda res:http_errors.append(str(res.status)+" "+res.url)
                            if res.status>=400 else None)
                    url=f"http://127.0.0.1:{server.server_port}/build/imo182-qrt/d3/explain/core1a.html"
                    response=page.goto(url,wait_until="load")
                    require(response is not None and response.status==200,"Core1A native page not served")
                    role=page.locator("html[data-g9-role='CORE1A']")
                    require(role.count()==1,"not native CORE1A page")
                    require(page.locator("body[data-blueprint-ref]").get_attribute("data-blueprint-ref")==EXPECTED_BP,
                            "Core1A generated page not registered blueprint")
                    sheets=page.evaluate("() => [...document.querySelectorAll('link[rel=stylesheet]')].map(e=>Boolean(e.sheet))")
                    require(len(sheets)>=2 and all(sheets),"Core1A CSS not loaded from original public assets")
                    require(page.locator("[data-g9-component='CONSTRUCTION_STEPS']").is_visible(),
                            "Core1A teaching construction invisible")
                    require(page.locator("[data-g9-component='TRAP_REPAIR']").is_visible(),
                            "Core1A misconception/repair invisible")
                    require(page.locator("[data-g9-block='exit_task']").is_visible(),
                            "Core1A changed-case independent exit invisible")
                    exit_text=page.locator("[data-g9-block='exit_task']").inner_text()
                    require("sqrt(z+6)=z" in exit_text and "z=-2" in exit_text and "z=3" in exit_text,
                            "independent exit not actually different from target problem")
                    require(page.locator("svg[role=img][aria-label]").count()>=1,
                            "Core1A teaching visual has no accessible name")
                    descriptions=page.locator("svg[role=img]").evaluate_all(
                        "nodes => nodes.map(n => ({name:n.getAttribute('aria-label')||'',desc:n.querySelector('desc')?.textContent||''}))")
                    require(all(a["name"] and a["desc"] for a in descriptions),
                            "Core1A teaching figure has missing accessible description")
                    metrics=page.evaluate("() => ({width:innerWidth,scroll:document.documentElement.scrollWidth})")
                    require(metrics["scroll"]<=width+2,"Core1A page overflows viewport")
                    article=page.locator("article[data-g9-unit]")
                    details=article.locator("details[data-g9-reveal][data-requires-attempt]").last
                    slot=details.locator("[data-g9-payload-slot]")
                    text_box=article.locator("[data-g9-attempt]").first
                    commit=article.locator("[data-g9-commit]").first
                    require(details.count()==1 and text_box.count()==1 and commit.count()==1,
                            "Core1A lacks a real protected independent exit")
                    require(slot.inner_text().strip()=="","Core1A exit answer already visible before attempt")
                    before=snapshot(page,OUTPUT/"screenshots"/f"core1a-explain-{width}-initial.png")
                    result={"viewport":width,"css_loaded":sheets,
                            "horizontal_overflow":False,"has_separate_changed_case_exit":True,
                            "svg_accessibility":descriptions,"initial_screenshot":before}
                    if width==390:
                        stages=article.locator("[data-g9-stage-goto]")
                        require(stages.count()>=3,"Core1A did not render staged concept construction")
                        stages.last.click()
                        result["stage_three"]=snapshot(page,OUTPUT/"screenshots"/"core1a-explain-390-stage3.png")
                        commit.click()
                        require(article.get_attribute("data-attempted")!="1",
                                "blank Core1A exit wrongly unlocked")
                        require(slot.inner_text().strip()=="","blank attempt exposed model answer")
                        result["blank_exit_blocked"]=True
                        text_box.fill("The principal square root is nonnegative. The candidate -2 fails; z=3 passes the original check.")
                        commit.click()
                        require(article.get_attribute("data-attempted")=="1",
                                "nonblank Core1A independent exit not committed")
                        details.locator("summary").click()
                        answer=slot.inner_text()
                        require("Only z=3" in answer and "z=-2" in answer,
                                "Core1A changed-case answer did not reveal after actual attempt")
                        result["nonblank_exit_revealed"]=True
                        result["after_attempt_screenshot"]=snapshot(page,OUTPUT/"screenshots"/"core1a-explain-390-afterattempt.png")
                        result["visible_exit_answer_sha256"]=hashlib.sha256(answer.encode()).hexdigest()
                    require(not errors and not failed and not http_errors,
                            f"Core1A learner runtime asset/script errors {errors} {failed} {http_errors}")
                    observations.append(result)
                    page.close()
            finally:
                browser.close()
    finally:
        server.shutdown()
        server.server_close()
        thread.join(timeout=5)
    return observations

