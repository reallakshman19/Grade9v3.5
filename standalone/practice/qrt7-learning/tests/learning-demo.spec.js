/**
 * Playwright browser test suite for G9O5-3 P2 Diagnostic-to-Learning Prototype.
 * Executes in real Chrome via `chromium.launch({ channel: 'chrome' })` over `file://` protocol.
 * Verifies:
 * - Zero console errors.
 * - Mobile responsive at 390px width with no horizontal scroll.
 * - Phase 1: Real P1 page driving to generate genuine P1 export JSON (v1.0).
 * - Demo Step 1: Fresh diagnostic with Sure + blank optional Why (v1.1 export).
 * - Demo Step 2: Import genuine P1 export, verify 7 evidence rows, hypothetical distractors, recognition limits, no mastery.
 * - Demo Step 3: Guided Lesson (SYNTHESIZE D1) covering all 4 stages (whole, part, distinguish, explain).
 * - Demo Step 4: Fresh Same-Cell Re-Check (35 N case) unassisted commit (14 N left) + practice retry.
 * - Demo Step 5: Save and reopen P2 record (v2.0), verify raw parent, profile, guided work, recheck, and 28 cells survive.
 */

const { chromium } = require('playwright');
const path = require('path');
const fs = require('fs');

async function runTests() {
  console.log('=== Starting G9O5-3 P2 Real Chrome Browser Test Suite ===');
  let passedCount = 0;
  let failedCount = 0;

  function assert(condition, message) {
    if (!condition) {
      console.error(`  FAIL: ${message}`);
      failedCount++;
      throw new Error(message);
    } else {
      console.log(`  PASS: ${message}`);
      passedCount++;
    }
  }

  const p1HtmlPath = path.resolve(__dirname, '..', '..', 'qrt7-diagnostic', 'index.html');
  const p2HtmlPath = path.resolve(__dirname, '..', 'index.html');
  const p1FileUrl = 'file:///' + p1HtmlPath.replace(/\\/g, '/');
  const p2FileUrl = 'file:///' + p2HtmlPath.replace(/\\/g, '/');

  const shotsDir = path.resolve(__dirname, 'shots');
  if (!fs.existsSync(shotsDir)) {
    fs.mkdirSync(shotsDir, { recursive: true });
  }

  console.log(`P1 Target URL: ${p1FileUrl}`);
  console.log(`P2 Target URL: ${p2FileUrl}`);

  const browser = await chromium.launch({
    channel: 'chrome',
    headless: true
  });

  const context = await browser.newContext({
    viewport: { width: 1200, height: 900 }
  });

  const page = await context.newPage();

  // Track console errors
  const consoleErrors = [];
  page.on('console', msg => {
    if (msg.type() === 'error') {
      console.error(`Browser console error: ${msg.text()}`);
      consoleErrors.push(msg.text());
    }
  });
  page.on('pageerror', err => {
    console.error(`Browser page error: ${err.message}`);
    consoleErrors.push(err.message);
  });

  try {
    // -------------------------------------------------------------
    // PHASE 1: Drive Real P1 Page to Generate Genuine P1 Export
    // -------------------------------------------------------------
    console.log('\n--- Phase 1: Drive Real P1 Page to Generate Genuine P1 Export (1.0) ---');
    await page.goto(p1FileUrl, { waitUntil: 'load' });
    assert(await page.title() === "Newton's Laws · Touching Blocks · Diagnostic (D1)", 'P1 page loaded');

    // Synthetic trial answers:
    // Q1 (APPLY): Option D (correct), Sure, "-"
    // Q2 (SYNTHESIZE): Option B (wrong 9 N), Sure, "-"
    // Q3 (REPRESENT): Option B (correct), Unsure, "synthetic diagram check"
    // Q4 (MODEL): Option A (correct), Sure, "-"
    // Q5 (EXPLAIN): Option C (correct), Unsure, "-"
    // Q6 (JUSTIFY): Option A (correct), Sure, "table check"
    // Q7 (RETRIEVE): Option C (correct), Sure, "third law"

    const p1Steps = [
      { val: 'D', conf: 'Sure', why: '-' },
      { val: 'B', conf: 'Sure', why: '-' },
      { val: 'B', conf: 'Unsure', why: 'synthetic diagram check' },
      { val: 'A', conf: 'Sure', why: '-' },
      { val: 'C', conf: 'Unsure', why: '-' },
      { val: 'A', conf: 'Sure', why: 'table check' },
      { val: 'C', conf: 'Sure', why: 'third law' }
    ];

    for (let i = 0; i < p1Steps.length; i++) {
      const s = p1Steps[i];
      await page.locator(`.option-card input[value="${s.val}"]`).click();
      await page.locator(`.confidence-btn[data-val="${s.conf}"]`).click();
      await page.fill('#why-input', s.why);
      await page.locator('#btn-next').click();
      await page.waitForTimeout(100);
    }

    // Submission on P1
    const p1DownloadPromise = page.waitForEvent('download');
    await page.click('#btn-download-json');
    const p1Download = await p1DownloadPromise;
    const genuineP1Path = path.join(shotsDir, 'genuine-p1-export.json');
    await p1Download.saveAs(genuineP1Path);
    assert(fs.existsSync(genuineP1Path), 'Genuine P1 export generated by driving real P1 page in Chrome');

    const genuineP1Json = JSON.parse(fs.readFileSync(genuineP1Path, 'utf8'));
    assert(genuineP1Json.record_version === '1.0', 'Genuine P1 record_version is 1.0');
    assert(genuineP1Json.responses.length === 7, 'Genuine P1 export contains exactly 7 responses');
    assert(genuineP1Json.responses[1].is_correct === false && genuineP1Json.responses[1].confidence === 'Sure',
      'P1 contains wrong + Sure (Q2 SYNTHESIZE)');
    assert(genuineP1Json.responses[0].is_correct === true && genuineP1Json.responses[0].confidence === 'Sure',
      'P1 contains correct + Sure (Q1 APPLY)');
    assert(genuineP1Json.responses[2].is_correct === true && genuineP1Json.responses[2].confidence === 'Unsure',
      'P1 contains correct + Unsure (Q3 REPRESENT)');
    assert(genuineP1Json.responses[0].why_text === '-', 'P1 contains "-" placeholder why');

    // -------------------------------------------------------------
    // PHASE 2: Test P2 Entry & 390px Mobile Viewport Check
    // -------------------------------------------------------------
    console.log('\n--- Phase 2: Test P2 Entry Screen & 390px Responsiveness ---');
    await page.goto(p2FileUrl, { waitUntil: 'load' });
    assert(await page.title() === "Newton's Laws · Touching Blocks · Learning Loop (P2)", 'P2 page loaded');

    // Test 390px width check
    await page.setViewportSize({ width: 390, height: 844 });
    await page.waitForTimeout(100);

    const hasHorizontalScroll = await page.evaluate(() => {
      return document.documentElement.scrollWidth > document.documentElement.clientWidth;
    });
    assert(!hasHorizontalScroll, 'Zero horizontal scroll at 390px mobile phone width');
    await page.screenshot({ path: path.join(shotsDir, 'shot-01-entry-mobile-390px.png'), fullPage: true });

    // Restore desktop viewport
    await page.setViewportSize({ width: 1200, height: 900 });

    // -------------------------------------------------------------
    // PHASE 3: Demo Step 1 — Fresh Diagnostic with Sure + Blank Why
    // -------------------------------------------------------------
    console.log('\n--- Phase 3: Demo Step 1 (Fresh Diagnostic with Sure + Blank Why) ---');
    await page.click('#btn-start-new-diagnostic');
    assert(await page.isVisible('#view-diagnostic'), 'Diagnostic view active');

    // Step through 7 questions with Sure and blank Why
    for (let q = 1; q <= 7; q++) {
      assert(await page.isVisible('#diag-question-stem'), `Question ${q} stem displayed`);
      
      // Select option A for each
      const optItem = page.locator('#diag-options-group .option-item').first();
      await optItem.click();

      // Select Sure
      await page.click('#diag-conf-sure');

      // Leave Why empty
      await page.fill('#diag-why-input', '');

      // Check evidence table visible on Q6
      if (q === 6) {
        assert(await page.isVisible('#diag-evidence-table-container'), 'Evidence table displayed on Q6 JUSTIFY');
      }

      // Next / Submit
      await page.click('#btn-diag-next');
      await page.waitForTimeout(60);
    }

    assert(await page.isVisible('#view-profile'), 'Submitted diagnostic and transitioned to Profile view');
    await page.screenshot({ path: path.join(shotsDir, 'shot-02-fresh-diagnostic-profile.png'), fullPage: true });

    // Verify fresh diagnostic export v1.1
    const p2DiagDownloadPromise = page.waitForEvent('download');
    await page.click('#btn-download-diag-json');
    const p2DiagDownload = await p2DiagDownloadPromise;
    const freshDiagPath = path.join(shotsDir, 'fresh-diag-v1.1-export.json');
    await p2DiagDownload.saveAs(freshDiagPath);
    assert(fs.existsSync(freshDiagPath), 'Fresh diagnostic export v1.1 downloaded');

    const freshDiagJson = JSON.parse(fs.readFileSync(freshDiagPath, 'utf8'));
    assert(freshDiagJson.record_version === '1.1', 'Fresh diagnostic record_version is 1.1');
    assert(freshDiagJson.why_requirement === 'optional', 'Fresh diagnostic why_requirement is optional');
    assert(freshDiagJson.responses.every(r => r.why_text === '' && r.why_status === 'omitted'),
      'All responses preserved empty string and why_status=omitted');

    // -------------------------------------------------------------
    // PHASE 4: Demo Step 2 — Open Genuine P1 Export
    // -------------------------------------------------------------
    console.log('\n--- Phase 4: Demo Step 2 (Open Genuine P1 Export & Verify Evidence Rows) ---');
    await page.goto(p2FileUrl, { waitUntil: 'load' });
    
    // Set genuine P1 file in file input
    const fileChooserInput = page.locator('#input-file-diagnostic');
    await fileChooserInput.setInputFiles(genuineP1Path);
    await page.waitForTimeout(100);

    assert(await page.isVisible('#view-profile'), 'Profile view opened from genuine P1 export');
    await page.screenshot({ path: path.join(shotsDir, 'shot-03-imported-p1-profile.png'), fullPage: true });

    // Verify exact original record preserved
    const profileText = await page.textContent('#view-profile');
    assert(profileText.includes('imported_p1_v1.0'), 'Original P1 provenance recorded');

    // Verify 7 rows present
    const rowCards = await page.locator('#profile-evidence-rows .evidence-row-card').count();
    assert(rowCards === 7, `Profile view displays exactly 7 evidence rows (found: ${rowCards})`);

    // Verify row 2 (SYNTHESIZE D1) is Needs Practice (wrong + Sure)
    const row2Text = await page.textContent('#evidence-row-2');
    assert(row2Text.includes('Needs practice') && row2Text.includes('Sure'),
      'Row 2 (SYNTHESIZE) correctly describes Needs practice with Sure confidence');
    assert(row2Text.includes('NET_FORCE_CONFUSED_WITH_CONTACT'),
      'Row 2 displays bank distractor tag NET_FORCE_CONFUSED_WITH_CONTACT');
    assert(row2Text.includes('Hypothetical interpretation (possibility only)'),
      'Row 2 explicitly labels distractor as hypothetical interpretation');

    // Verify row 1 is Correct and sure, with "-" flagged as placeholder
    const row1Text = await page.textContent('#evidence-row-1');
    assert(row1Text.includes('Correct and sure — one question'),
      'Row 1 displays "Correct and sure — one question"');
    assert(row1Text.includes('placeholder reasoning'),
      'Row 1 flags "-" as placeholder reasoning without altering source');

    // Verify row 3 is Correct, unsure
    const row3Text = await page.textContent('#evidence-row-3');
    assert(row3Text.includes('Correct, unsure'), 'Row 3 displays "Correct, unsure"');

    // Verify EXPLAIN and JUSTIFY have explicit evidence limitation
    const row5Text = await page.textContent('#evidence-row-5');
    const row6Text = await page.textContent('#evidence-row-6');
    assert(row5Text.includes('demonstrates recognition only') || row6Text.includes('demonstrates recognition only') ||
           row5Text.includes('candidate route') || row6Text.includes('candidate route'),
      'Evidence limitation note recorded for EXPLAIN/JUSTIFY');

    // Verify NO row or cell is labelled mastered
    const statusBadges = await page.locator('#profile-evidence-rows .status-badge').allTextContents();
    const cellLabels = await page.locator('#profile-coverage-wrapper .cell-box').allTextContents();
    const hasMasteredBadge = statusBadges.some(b => b.toLowerCase().includes('mastered'));
    const hasMasteredCell = cellLabels.some(c => c.toLowerCase().includes('mastered'));
    assert(!hasMasteredBadge && !hasMasteredCell, 'No type row or cell is labelled mastered');

    // Verify 28-cell coverage grid
    const assessedCells = await page.locator('.cell-box.assessed').count();
    const unassessedCells = await page.locator('.cell-box.unassessed').count();
    assert(assessedCells === 7, `Coverage grid has exactly 7 assessed D1 cells (found: ${assessedCells})`);
    assert(unassessedCells === 21, `Coverage grid has exactly 21 unassessed cells (found: ${unassessedCells})`);

    // -------------------------------------------------------------
    // PHASE 5: Demo Step 3 — Guided Lesson (SYNTHESIZE D1)
    // -------------------------------------------------------------
    console.log('\n--- Phase 5: Demo Step 3 (Guided Pilot Lesson SYNTHESIZE D1) ---');
    await page.click('#btn-open-lesson');
    assert(await page.isVisible('#view-lesson'), 'Lesson view active');

    // Verify lesson target and entry message
    const lessonText = await page.textContent('#view-lesson');
    assert(lessonText.includes('Choose and connect a route from the combined system to an individual block'),
      'Lesson target displayed verbatim');
    assert(lessonText.includes("distinguish its net force from its contact force"),
      'Net force vs contact force distinction displayed');

    // Stage 1: whole
    assert(await page.isVisible('#lesson-stage-1'), 'Stage 1 (whole) visible');
    await page.click('#s1-opt-a'); // choose combined system A+B
    assert(await page.isVisible('#stage-1-feedback'), 'Stage 1 feedback displayed');
    const s1FbText = await page.textContent('#stage-1-feedback');
    assert(s1FbText.includes('4 m/s² right'), 'Stage 1 shows acceleration 4 m/s² right');
    await page.click('#btn-stage-1-next');

    // Stage 2: part
    assert(await page.isVisible('#lesson-stage-2'), 'Stage 2 (part) visible');
    await page.click('#s2-opt-a'); // choose C = 3 * 4 = 12 N right
    assert(await page.isVisible('#stage-2-feedback'), 'Stage 2 feedback displayed');
    const s2FbText = await page.textContent('#stage-2-feedback');
    assert(s2FbText.includes('12 N right') && s2FbText.includes('12 N left'),
      'Stage 2 shows contact force 12 N right and reciprocal 12 N left');
    await page.click('#btn-stage-2-next');

    // Stage 3: distinguish
    assert(await page.isVisible('#lesson-stage-3'), 'Stage 3 (distinguish) visible');
    await page.click('#s3-opt-a'); // choose "A's net force"
    assert(await page.isVisible('#stage-3-feedback'), 'Stage 3 feedback displayed');
    const s3FbText = await page.textContent('#stage-3-feedback');
    assert(s3FbText.includes('8 N right') && s3FbText.includes("A's net force"),
      'Stage 3 distinguishes 8 N net force from 12 N contact force');
    await page.click('#btn-stage-3-next');

    // Stage 4: explain
    assert(await page.isVisible('#lesson-stage-4'), 'Stage 4 (reconstruct & explain) visible');
    
    // Peek equations to verify guided assistance tracking
    await page.click('#btn-peek-equations');
    assert(await page.isVisible('#peeked-equations-box'), 'Equations revealed on peek');

    // Provide synthetic explanation
    await page.fill('#lesson-explain-input',
      'Acceleration is 20/5 = 4 m/s^2. For B, C = 3*4 = 12 N right, so B pushes A with 12 N left. A net force is 20-12 = 8 N.');
    await page.click('#btn-save-explanation');

    assert(await page.isVisible('#stage-4-comparison'), 'Comparison card displayed');
    const compText = await page.textContent('#stage-4-comparison');
    assert(compText.includes('Compare with:') && compText.includes('isolate B to get its contact force'),
      'Comparison route provided');
    assert(compText.includes('guided learning'), 'Saved attempt explicitly marked as guided learning');
    await page.screenshot({ path: path.join(shotsDir, 'shot-04-guided-lesson-complete.png'), fullPage: true });

    // Advance to Re-Check
    await page.click('#btn-proceed-recheck');

    // -------------------------------------------------------------
    // PHASE 6: Demo Step 4 — Fresh Same-Cell Re-Check (35 N Problem)
    // -------------------------------------------------------------
    console.log('\n--- Phase 6: Demo Step 4 (Fresh Same-Cell Re-Check: 35 N Problem) ---');
    assert(await page.isVisible('#view-recheck'), 'Re-check view active');

    // Verify stem
    const rcStemText = await page.textContent('#recheck-stem');
    assert(rcStemText.includes('35 N horizontal push') && rcStemText.includes('A (3 kg') && rcStemText.includes('B (2 kg'),
      'Fresh problem stem correctly changes masses to 3 kg / 2 kg and force to 35 N');

    // Verify unassisted: no hints/routes before commitment
    const rcPreCommit = await page.textContent('#view-recheck');
    assert(!rcPreCommit.includes('7 m/s²') && !rcPreCommit.includes('14 N to the left. (Correct)'),
      'No route, intermediate acceleration or correct answer exposed before commitment');

    // Answer correctly: Option C (14 N to the left)
    await page.click('#rc-opt-c');
    await page.click('#rc-conf-sure');
    await page.fill('#recheck-why-input', 'a = 35/(3+2) = 7 m/s^2; B contact = 2 * 7 = 14 N right, reciprocal on A is 14 N left.');

    await page.click('#btn-recheck-commit');
    assert(await page.isVisible('#recheck-feedback-area'), 'Post-commit feedback card visible');

    const rcFeedbackText = await page.textContent('#recheck-feedback-area');
    assert(rcFeedbackText.includes('Correct: 14 N to the left'), 'Correct answer 14 N confirmed post-commit');
    assert(rcFeedbackText.includes('never auto-declares mastery or promotes to D2'),
      'Recheck explicitly maintains single-item observation, no automatic promotion');
    await page.screenshot({ path: path.join(shotsDir, 'shot-05-recheck-feedback-correct.png'), fullPage: true });

    // Test retry after solution exposed: marked as practice
    await page.click('#btn-recheck-retry');
    await page.click('#rc-opt-b'); // wrong 21 N
    await page.click('#rc-conf-sure');
    await page.click('#btn-recheck-commit');

    const practiceFbText = await page.textContent('#recheck-feedback-area');
    assert(practiceFbText.includes('Needs Practice') && practiceFbText.includes('21 N'),
      'Solution-exposed retry executed and distractor hypothesis displayed');
    await page.screenshot({ path: path.join(shotsDir, 'shot-06-recheck-practice-retry.png'), fullPage: true });

    // Advance to Summary
    await page.click('#btn-recheck-view-summary');

    // -------------------------------------------------------------
    // PHASE 7: Demo Step 5 — Save and Reopen Linked P2 Record (v2.0)
    // -------------------------------------------------------------
    console.log('\n--- Phase 7: Demo Step 5 (Save & Reopen Linked P2 Record v2.0) ---');
    assert(await page.isVisible('#view-summary'), 'Summary view active');

    // Verify sections
    assert(await page.isVisible('#summary-parent-evidence'), 'Frozen parent diagnostic evidence rendered');
    assert(await page.isVisible('#summary-guided-card'), 'Guided unit summary rendered');
    assert(await page.isVisible('#summary-recheck-card'), 'Fresh recheck summary rendered');
    assert(await page.isVisible('#summary-coverage-wrapper'), '28-cell updated coverage rendered');

    // Download P2 Record
    const p2DownloadPromise = page.waitForEvent('download');
    await page.click('#btn-download-p2-json');
    const p2Download = await p2DownloadPromise;
    const p2RecordPath = path.join(shotsDir, 'p2-session-downloaded.json');
    await p2Download.saveAs(p2RecordPath);
    assert(fs.existsSync(p2RecordPath), 'P2 session record downloaded as JSON');

    const p2Json = JSON.parse(fs.readFileSync(p2RecordPath, 'utf8'));
    assert(p2Json.record_version === '2.0', 'P2 record_version is 2.0');
    assert(p2Json.phase === 'learn_recheck', 'P2 phase is learn_recheck');
    assert(p2Json.parent_diagnostic && p2Json.parent_diagnostic.raw_record, 'Parent raw record preserved intact');
    assert(p2Json.parent_diagnostic.parent_hash_sha256.length === 64, 'Parent SHA-256 hash stored');
    assert(p2Json.guided_unit && p2Json.guided_unit.stages_completed.length === 4, 'All 4 guided stages saved');
    assert(p2Json.recheck_response && p2Json.recheck_response.is_correct === true, 'First unassisted recheck answer saved');
    assert(p2Json.recheck_response.selected_option_id === 'C', 'Recheck selected option is C (14 N)');
    assert(p2Json.recheck_response.help_before_commit === false, 'Recheck help_before_commit is false');
    assert(p2Json.recheck_practice_attempts.length >= 1, 'Solution-exposed practice attempts tracked separately');
    assert(p2Json.coverage_map_28.length === 28, 'Coverage map contains exactly 28 cells');

    const synD1Cell = p2Json.coverage_map_28.find(c => c.cell_id === 'SYNTHESIZE-D1');
    assert(synD1Cell && synD1Cell.evidence.length >= 2, 'SYNTHESIZE-D1 preserves both diagnostic and recheck evidence');

    // Reopen P2 record on Entry screen
    await page.click('#btn-summary-home');
    assert(await page.isVisible('#view-entry'), 'Returned to Entry screen');

    await fileChooserInput.setInputFiles(p2RecordPath);
    await page.waitForTimeout(100);

    assert(await page.isVisible('#view-summary'), 'Reopened P2 session JSON restored Summary view');
    const reopenedSummaryText = await page.textContent('#view-summary');
    assert(reopenedSummaryText.includes(p2Json.attempt_id), 'Reopened P2 session attempt ID matches');
    assert(reopenedSummaryText.includes('Option C') && reopenedSummaryText.includes('14 N left'),
      'Reopened P2 session restores fresh recheck evidence');
    await page.screenshot({ path: path.join(shotsDir, 'shot-07-reopened-p2-session.png'), fullPage: true });

    // Check console errors
    assert(consoleErrors.length === 0, `Zero console errors throughout test run (found: ${consoleErrors.length})`);

    console.log('\n======================================================');
    console.log(`P2 TEST SUITE FINISHED: ${passedCount} PASSED, ${failedCount} FAILED.`);
    console.log('======================================================');

  } catch (err) {
    console.error('Test run failed with error:', err);
    await page.screenshot({ path: path.join(shotsDir, 'shot-error-failure.png') });
    failedCount++;
  } finally {
    await browser.close();
  }

  if (failedCount > 0) {
    process.exit(1);
  }
}

runTests();
